// 从 crate 根模块引入 AppState（全局应用状态，通常包含配置、数据库连接、服务实例等）
use crate::AppState;

// `#[expect(...)]` 是 `#[allow(...)]` 的"承诺版"：如果该 lint 实际没有触发，编译器会警告，防止过期的豁免。
// 这里豁免 `clippy::allow_attributes_without_reason`：要求所有 `allow` 属性必须带 `reason`。
// 但 security.rs 内部还有一个遗留的模块级动态 JSON 豁免没写 reason，
// 所以在此边界上临时豁免这条规则，把技术债限制在 security.rs 附近，等待响应 DTO 改造完成。
#[expect(
    clippy::allow_attributes_without_reason,
    reason = "security.rs still contains a legacy module-level dynamic-JSON exception; keep the debt scoped to that boundary until the response DTO conversion is complete"
)]
// 声明 security 子模块为公开模块（本 crate 外部可见）
pub mod security;

// 引入 axum 相关类型：
// - StatusCode：HTTP 状态码
// - middleware：中间件工具（from_fn_with_state）
// - IntoResponse：把类型转成 HTTP 响应
// - get：GET 路由辅助函数
// - Router：路由器
use axum::{http::StatusCode, middleware, response::IntoResponse, routing::get, Router};

// 声明 auth 子模块（公开）：认证相关路由与中间件
pub mod auth;
// 声明 billing 子模块（公开）：计费相关路由
pub mod billing;
// 声明 channel 子模块（公开）：渠道管理路由
pub mod channel;
// 声明 log 子模块（公开）：日志相关路由
pub mod log;
// 声明 monitor 子模块（公开）：监控相关路由
pub mod monitor;
// 声明 node_deployment 子模块（crate 内可见）：节点部署路由（见之前分析的 use crateAppState 文件）
pub(crate) mod node_deployment;
// 再次豁免 lint：openapi 模块里有两个遗留的静态 JSON 构造器，
// 里面包含范围很窄的动态 JSON 豁免，且函数过长（too_many_lines）。
// 这里把豁免仅限定在 openapi 模块，等待生成器被拆分。
#[expect(
    clippy::allow_attributes_without_reason,
    clippy::too_many_lines,
    reason = "OpenAPI JSON is generated by two legacy static builders with narrowly-scoped dynamic-JSON exceptions; baseline only this module while the generator is decomposed"
)]
// 声明 openapi 子模块（公开）：OpenAPI 文档路由
pub mod openapi;
// 声明 response 子模块（公开）：统一响应结构与工具
pub mod response;
// 声明 token 子模块（公开）：API token 管理路由
pub mod token;
// 声明 user 子模块（公开）：用户管理路由
pub mod user;

/// Fallback handler for unmatched /console/api/* requests
/// Returns 404 instead of being caught by LiveView's catch-all
// 兜底处理函数：匹配不到的 /console/api/* 请求会走到这里
// 返回 404，而不是被 LiveView 的 catch-all 路由捕获并返回 HTML 页面
async fn api_not_found() -> impl IntoResponse {
    // 返回 404 状态码 + 纯文本消息
    (StatusCode::NOT_FOUND, "API endpoint not found")
}

// 构建整个应用的路由树
// 参数 state：应用全局状态（会被克隆分发给各个子路由）
// 返回：Router（已注入状态，可直接交给 axum::serve）
pub fn routes(state: AppState) -> Router {
    // Public routes - no authentication required.
    // 公开路由：无需认证即可访问
    let public_routes = Router::new()
        // 合并 auth 模块的公开路由（如登录、注册等）
        .merge(auth::public_routes())
        // 合并节点部署路由（启动/查询/停止部署）
        .merge(node_deployment::routes())
        // 注入状态（克隆一份，避免后面被移动）
        .with_state(state.clone());

    // Administrator-only management surfaces. Authentication runs on the
    // outer protected router; this inner layer performs authorization.
    // 仅管理员可访问的管理路由：
    // 认证由外层 protected_routes 的 auth_middleware 完成，
    // 这一层只负责"授权"（判断是否为管理员）。
    let admin_routes = Router::new()
        // 渠道管理
        .merge(channel::routes())
        // 日志查看
        .merge(log::routes())
        // 监控
        .merge(monitor::routes())
        // 安全设置
        .merge(security::security_routes())
        // 叠加管理员授权中间件（携带状态）
        .layer(middleware::from_fn_with_state(
            state.clone(),
            auth::admin_middleware,
        ));

    // Authenticated self-service routes. Token handlers perform resource-level
    // owner/admin authorization because users are allowed to manage their own
    // API credentials while administrators may manage all credentials.
    // 需要登录的自助服务路由：
    // token 处理器内部做"资源级"授权（所有者或管理员），
    // 因为普通用户可以管理自己的 API 凭证，管理员可以管理所有凭证。
    let protected_routes = Router::new()
        // 认证相关受保护路由（如登出、改密）
        .merge(auth::protected_routes())
        // 计费
        .merge(billing::routes())
        // Token 管理
        .merge(token::routes())
        // 用户管理
        .merge(user::routes())
        // OpenAPI 文档
        .merge(openapi::routes())
        // 嵌套管理路由（此时 admin_routes 已带 admin_middleware）
        .merge(admin_routes)
        // Catch-all for any unmatched /console/api/* paths. This prevents
        // LiveView from returning HTML for non-existent API endpoints.
        // 兜底路由：任何未匹配的 /console/api/* 路径都返回 JSON 风格的 404，
        // 避免被 LiveView 的 catch-all 捕获后返回 HTML。
        // 注意 {*path} 是 axum 0.8+ 的通配语法（旧版为 *path）。
        .route("/console/api/{*path}", get(api_not_found))
        // 叠加认证中间件：所有 protected_routes 内的请求都必须先通过认证。
        // 由于 admin_routes 已经 merge 进来，管理员路由也受此认证保护，
        // 形成"先认证（外）→ 再授权（内）"的两层结构。
        .layer(middleware::from_fn_with_state(
            state.clone(),
            crate::auth_middleware,
        ))
        // 给受保护路由注入状态（注意这里 state 被 move，不再 clone）
        .with_state(state);

    // 合并公开路由与受保护路由，返回最终 Router
    // 注意：public_routes 和 protected_routes 都已 with_state，类型已一致
    public_routes.merge(protected_routes)
}
